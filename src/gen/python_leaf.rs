//! Render the checked IR as Python dataclasses and proc state machines.
use super::{cli_leaf, gen_leaf, sema_leaf};
use crate::vcc::types::*;
use std::collections::BTreeMap;
use std::fmt::Write;
use std::path::Path;
use std::process::Command;

const HEADER: &str = "# Code generated by vandorf. DO NOT EDIT.\n";
const RUNTIME: &str = include_str!("python_runtime.py");
const HTTP: &str = include_str!("python_http.py");

pub fn has_python(m: Manifest) -> Result<bool, String> {
    Ok(matches!(m.python, MaybePython::Some(_)))
}

pub fn tests(m: Manifest) -> Result<List<Str>, String> {
    Ok(match m.python {
        MaybePython::Some(p) => p.test,
        MaybePython::None => List::default(),
    })
}

pub fn server_names(m: Manifest, only: Str) -> Result<List<Str>, String> {
    let mut names: Vec<_> = m.http.keys().filter(|_| only.is_empty()).cloned().collect();
    names.sort();
    Ok(names.into())
}

pub fn generate(s: PythonInput) -> Result<PythonOutput, String> {
    let table = crate::vcc::run_build_table(s.prog.clone()).map_err(|e| e.to_string())?;
    let mut generator = Generator {
        prog: &s.prog,
        table,
        warnings: Vec::new(),
        implementations: BTreeMap::new(),
    };
    Ok(match generator.files(&s) {
        Ok(files) => PythonOutput {
            files: files.into(),
            warnings: generator.warnings.into(),
            error: MaybeStr::None,
        },
        Err(e) => PythonOutput {
            files: List::default(),
            warnings: List::default(),
            error: MaybeStr::Some(e.into()),
        },
    })
}

fn quote(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if c.is_control() => write!(out, "\\u{:04x}", c as u32).unwrap(),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn ident(s: &str) -> String {
    if s.starts_with("_vd_")
        || s.starts_with("__")
        || matches!(
            s,
            "False"
                | "None"
                | "True"
                | "_"
                | "as"
                | "assert"
                | "async"
                | "await"
                | "break"
                | "class"
                | "continue"
                | "def"
                | "del"
                | "elif"
                | "else"
                | "except"
                | "finally"
                | "for"
                | "from"
                | "global"
                | "if"
                | "import"
                | "in"
                | "is"
                | "lambda"
                | "nonlocal"
                | "not"
                | "or"
                | "pass"
                | "raise"
                | "return"
                | "try"
                | "while"
                | "with"
                | "yield"
                | "and"
        )
    {
        format!("_vd_{s}")
    } else {
        s.into()
    }
}

fn tup(items: impl IntoIterator<Item = String>) -> String {
    let items: Vec<_> = items.into_iter().collect();
    if items.len() == 1 {
        format!("({},)", items[0])
    } else {
        format!("({})", items.join(", "))
    }
}

fn line(out: &mut String, depth: usize, text: impl AsRef<str>) {
    writeln!(out, "{}{}", "    ".repeat(depth), text.as_ref()).unwrap();
}

struct PositionalArgs {
    minimum: usize,
    maximum: Option<usize>,
    requires_keywords_or_async: bool,
}

enum ModuleCheck {
    Missing,
    Signatures(BTreeMap<String, PositionalArgs>),
    Unchecked,
}

fn check_module(file: &str) -> Result<ModuleCheck, String> {
    if !Path::new(file).is_file() {
        return Ok(ModuleCheck::Missing);
    }
    for interpreter in ["python3", "python"] {
        let output = match Command::new(interpreter)
            .args(["-I", "-S", "-c", include_str!("python_check.py"), file])
            .output()
        {
            Ok(output) => output,
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => continue,
            Err(e) => return Err(format!("could not check Python implementation {file}: {e}")),
        };
        if !output.status.success() {
            return Err(format!(
                "could not check Python implementation {file}: {}",
                String::from_utf8_lossy(&output.stderr).trim()
            ));
        }
        let mut signatures = BTreeMap::new();
        for row in String::from_utf8_lossy(&output.stdout).lines() {
            let fields: Vec<_> = row.split('\t').collect();
            let [name, minimum, maximum, required] = fields.as_slice() else {
                return Err(format!("invalid signature check output for {file}"));
            };
            let count = |s: &str| {
                s.parse()
                    .map_err(|_| format!("invalid argument count for {file}"))
            };
            signatures.insert(
                (*name).to_owned(),
                PositionalArgs {
                    minimum: count(minimum)?,
                    maximum: if *maximum == "*" {
                        None
                    } else {
                        Some(count(maximum)?)
                    },
                    requires_keywords_or_async: *required == "1",
                },
            );
        }
        return Ok(ModuleCheck::Signatures(signatures));
    }
    Ok(ModuleCheck::Unchecked)
}

struct Generator<'a> {
    prog: &'a Program,
    table: Table,
    warnings: Vec<Str>,
    implementations: BTreeMap<Str, ModuleCheck>,
}

impl Generator<'_> {
    fn render(&self, ty: &TyRef, qual: &str) -> String {
        match ty {
            TyRef::Prim(p) => match &**p {
                "void" => "type(None)".into(),
                "string" => "str".into(),
                _ => p.to_string(),
            },
            TyRef::Array(t) => format!("tuple[{}, ...]", self.render(t, qual)),
            TyRef::Map(m) => format!(
                "dict[{}, {}]",
                self.render(&m.key, qual),
                self.render(&m.value, qual)
            ),
            TyRef::Named(n) => format!("{qual}{}", ident(&self.table.types[*n as usize].name)),
        }
    }

    fn ty(&self, t: &Type) -> Result<String, String> {
        Ok(self.render(&gen_leaf::get(self.table.clone(), t.clone())?, "_vd_types."))
    }

    fn unfold(&self, t: &Type) -> Result<Type, String> {
        gen_leaf::unfolded(self.prog.types.clone(), t.clone())
    }

    fn member(&self, t: &Type, name: &Str) -> Result<Type, String> {
        gen_leaf::member_of(self.prog.types.clone(), t.clone(), name.clone())
    }

    fn params(&self, id: i64) -> Result<List<Member>, String> {
        sema_leaf::node_params(self.prog.nodes.clone(), id)
    }

    fn ret(&self, id: i64) -> Result<Type, String> {
        sema_leaf::node_ret(self.prog.nodes.clone(), id)
    }

    fn name(&self, id: i64) -> Result<String, String> {
        Ok(sema_leaf::qual_name(self.prog.nodes[id as usize].clone())?.to_string())
    }

    fn proc_name(&self, id: i64) -> Result<String, String> {
        Ok(format!(
            "run_{}",
            gen_leaf::snake_gname(self.prog.nodes[id as usize].clone())?
        ))
    }

    fn callable(&self, id: i64) -> Result<String, String> {
        let base = gen_leaf::base_of(self.prog.nodes.clone(), id)?;
        match &self.prog.nodes[base as usize].kind {
            NodeKind::Proc(_) => self.proc_name(base),
            NodeKind::Func(_) => Ok(format!("_func_{base}")),
            NodeKind::Id(_) => Ok("_identity".into()),
            _ => Err(format!("{} is not callable", self.name(id)?)),
        }
    }

    fn types(&self) -> String {
        let mut out = format!(
            "{HEADER}from __future__ import annotations\nfrom dataclasses import dataclass as _vd_dataclass\nfrom typing import ClassVar as _vd_classvar\n\n"
        );
        for (i, ty) in self.table.types.iter().enumerate() {
            let name = ident(&ty.name);
            match &ty.shape {
                Shape::Struct(fields) => {
                    line(&mut out, 0, "@_vd_dataclass(frozen=True, slots=True)");
                    line(&mut out, 0, format!("class {name}:"));
                    let attrs = fields
                        .iter()
                        .map(|f| format!("{}: {}", quote(&f.name), quote(&ident(&f.name))))
                        .collect::<Vec<_>>();
                    line(
                        &mut out,
                        1,
                        format!(
                            "__vandorf_fields__: _vd_classvar = {{{}}}",
                            attrs.join(", ")
                        ),
                    );
                    for field in fields.iter() {
                        line(
                            &mut out,
                            1,
                            format!("{}: {}", ident(&field.name), self.render(&field.r, "")),
                        );
                    }
                }
                Shape::Enum(variants) => {
                    line(&mut out, 0, format!("class {name}:"));
                    line(&mut out, 1, "__slots__ = ()");
                    let mut tags = Vec::new();
                    for (j, field) in variants.iter().enumerate() {
                        let variant = format!("_vd_variant_{i}_{j}");
                        out.push('\n');
                        line(&mut out, 0, "@_vd_dataclass(frozen=True, slots=True)");
                        line(&mut out, 0, format!("class {variant}({name}):"));
                        line(
                            &mut out,
                            1,
                            format!("__vandorf_tag__: _vd_classvar = {}", quote(&field.name)),
                        );
                        if !matches!(&field.r, TyRef::Prim(p) if &**p == "void") {
                            line(
                                &mut out,
                                1,
                                format!("_vd_payload: {}", self.render(&field.r, "")),
                            );
                        }
                        line(
                            &mut out,
                            0,
                            format!("{name}.{} = {variant}", ident(&field.name)),
                        );
                        tags.push(format!("{}: {variant}", quote(&field.name)));
                    }
                    line(
                        &mut out,
                        0,
                        format!("{name}.__vandorf_variants__ = {{{}}}", tags.join(", ")),
                    );
                }
            }
            out.push('\n');
        }
        for alias in self.table.aliases.iter() {
            line(
                &mut out,
                0,
                format!("{} = {}", ident(&alias.name), self.render(&alias.r, "")),
            );
        }
        out
    }

    fn args(&self, c: &Call) -> Result<String, String> {
        Ok(tup(c
            .args
            .iter()
            .map(|arg| self.expr(&arg.value, Some(&arg.param)))
            .collect::<Result<Vec<_>, _>>()?))
    }

    fn invoke(&self, c: &Call) -> Result<String, String> {
        Ok(format!(
            "_vd_runtime.invoke({}, {}, {})",
            quote(&self.name(c.target)?),
            self.callable(c.target)?,
            self.args(c)?
        ))
    }

    fn cast(&self, text: String, from: &Type, to: Option<&Type>) -> Result<String, String> {
        if let Some(to) = to {
            let dest = self.ty(to)?;
            if self.ty(from)? != dest {
                return Ok(format!("_vd_runtime.value({text}, {dest})"));
            }
        }
        Ok(text)
    }

    fn expr(&self, e: &Expr, want: Option<&Type>) -> Result<String, String> {
        let own = |e| self.expr(e, None);
        let expected = || want.ok_or_else(|| "Python: literal without a type".to_string());
        Ok(match e {
            Expr::Ref(r) => {
                let mut expr = match r.root {
                    Root::This => "this".into(),
                    Root::Node(id) => format!("env[{id}]"),
                    Root::Bind => format!("b_{}", r.bind),
                };
                for field in r.fields.iter() {
                    write!(expr, ".{}", ident(field)).unwrap();
                }
                self.cast(expr, &r.ty, want)?
            }
            Expr::Int(i) => i.to_string(),
            Expr::Float(f) if f.is_finite() => format!("{f:?}"),
            Expr::Float(f) => format!("float({})", quote(&f.to_string())),
            Expr::Str(s) => quote(s),
            Expr::Bool(b) => if *b { "True" } else { "False" }.into(),
            Expr::Call(c) => self.cast(self.invoke(c)?, &self.ret(c.target)?, want)?,
            Expr::Variant(v) => {
                let t = expected()?;
                let payload = match &*v.payload {
                    MaybeExpr::Some(e) => self.expr(e, Some(&self.member(t, &v.tag)?))?,
                    MaybeExpr::None => String::new(),
                };
                format!("{}.{}({payload})", self.ty(t)?, ident(&v.tag))
            }
            Expr::Struct(fields) => {
                let t = expected()?;
                let fields = fields
                    .iter()
                    .map(|f| {
                        Ok(format!(
                            "{}={}",
                            ident(&f.name),
                            self.expr(&f.e, Some(&self.member(t, &f.name)?))?
                        ))
                    })
                    .collect::<Result<Vec<_>, String>>()?;
                format!("{}({})", self.ty(t)?, fields.join(", "))
            }
            Expr::Array(items) => {
                let t = want.map(|t| self.unfold(t)).transpose()?;
                let element = match &t {
                    Some(Type::Array(t)) => Some(&**t),
                    _ => None,
                };
                tup(items
                    .iter()
                    .map(|e| self.expr(e, element))
                    .collect::<Result<Vec<_>, _>>()?)
            }
            Expr::Map(items) => {
                let t = want.map(|t| self.unfold(t)).transpose()?;
                let (key, item) = match &t {
                    Some(Type::Map(m)) => (Some(&*m.key), Some(&*m.value)),
                    _ => (None, None),
                };
                let items = items
                    .iter()
                    .map(|e| {
                        Ok(format!(
                            "{}: {}",
                            self.expr(&e.key, key)?,
                            self.expr(&e.value, item)?
                        ))
                    })
                    .collect::<Result<Vec<_>, String>>()?;
                format!("{{{}}}", items.join(", "))
            }
            Expr::Unary(u) => format!(
                "({}{})",
                if &*u.op == "!" { "not " } else { "-" },
                own(&u.e)?
            ),
            Expr::Binary(b) => {
                let (left, right) = (own(&b.l)?, own(&b.r)?);
                match (&*b.op, &*b.operand) {
                    ("/", "int") => format!("_vd_runtime.div({left}, {right})"),
                    ("%", "int") => format!("_vd_runtime.rem({left}, {right})"),
                    ("&&", _) => format!("({left} and {right})"),
                    ("||", _) => format!("({left} or {right})"),
                    (op, _) => format!("({left} {op} {right})"),
                }
            }
            Expr::Index(i) => {
                let result = match self.unfold(&i.ty)? {
                    Type::Array(e) => (*e).clone(),
                    Type::Map(m) => (*m.value).clone(),
                    _ => return Err("Python: invalid index".into()),
                };
                self.cast(
                    format!(
                        "_vd_runtime.index({}, {})",
                        self.expr(&i.e, Some(&i.ty))?,
                        own(&i.key)?
                    ),
                    &result,
                    want,
                )?
            }
            Expr::Field(f) => self.cast(
                format!("({}).{}", self.expr(&f.e, Some(&f.ty))?, ident(&f.name)),
                &self.member(&f.ty, &f.name)?,
                want,
            )?,
            Expr::In(i) => format!("({} in {})", own(&i.key)?, own(&i.map)?),
            Expr::Query(q) => {
                let v = self.expr(&q.e, Some(&q.ty))?;
                match &*q.q {
                    "len" => {
                        if matches!(self.unfold(&q.ty)?, Type::Prim(t) if &*t == "string") {
                            format!("len(({v}).encode('utf-8'))")
                        } else {
                            format!("len({v})")
                        }
                    }
                    "keys" | "values" => format!("_vd_runtime.{}({v})", q.q),
                    k => return Err(format!("Python: unknown query {k}")),
                }
            }
            Expr::Merge(m) => {
                let op = if matches!(self.unfold(&m.ty)?, Type::Array(_)) {
                    "+"
                } else {
                    "|"
                };
                self.cast(
                    format!(
                        "({} {op} {})",
                        self.expr(&m.l, Some(&m.ty))?,
                        self.expr(&m.r, Some(&m.ty))?
                    ),
                    &m.ty,
                    want,
                )?
            }
            Expr::Remove(m) => self.cast(
                format!(
                    "_vd_runtime.remove({}, {})",
                    self.expr(&m.m, Some(&m.ty))?,
                    own(&m.keys)?
                ),
                &m.ty,
                want,
            )?,
        })
    }

    fn pattern(&self, p: &SPat) -> Result<String, String> {
        Ok(match &*p.kind {
            SPatKind::Wild => "_".into(),
            SPatKind::Bind(n) => format!("b_{n}"),
            SPatKind::Variant(v) => {
                let pattern = match &*v.payload {
                    MaybePat::None => String::new(),
                    MaybePat::Some(p) => self.pattern(p)?,
                };
                format!("{}.{}({pattern})", self.ty(&p.ty)?, ident(&v.tag))
            }
            SPatKind::Struct(fields) => {
                let fields = fields
                    .iter()
                    .map(|f| Ok(format!("{}={}", ident(&f.name), self.pattern(&f.pat)?)))
                    .collect::<Result<Vec<_>, String>>()?;
                format!("{}({})", self.ty(&p.ty)?, fields.join(", "))
            }
            SPatKind::Or(ps) => format!(
                "({})",
                ps.iter()
                    .map(|p| self.pattern(p))
                    .collect::<Result<Vec<_>, _>>()?
                    .join(" | ")
            ),
        })
    }

    fn transition(&self, out: &mut String, d: usize, c: &Call) -> Result<(), String> {
        line(
            out,
            d,
            format!("pc, args = {}, {}", c.target, self.args(c)?),
        );
        line(out, d, "continue");
        Ok(())
    }

    fn arms(&self, out: &mut String, d: usize, arms: &[SArm]) -> Result<(), String> {
        for arm in arms {
            let body_depth = match &arm.test {
                Test::Else => d,
                Test::Cond(e) => {
                    line(out, d, format!("if {}:", self.expr(e, None)?));
                    d + 1
                }
                Test::Pat(p) => {
                    line(out, d, "match this:");
                    line(out, d + 1, format!("case {}:", self.pattern(p)?));
                    d + 2
                }
            };
            match &arm.body {
                SBody::Call(c) => self.transition(out, body_depth, c)?,
                SBody::Switch(arms) => self.arms(out, body_depth, arms)?,
            }
        }
        line(
            out,
            d,
            "raise _vd_runtime.VandorfError('no switch arm matched')",
        );
        Ok(())
    }

    fn machine(&self, out: &mut String, pid: i64, p: &ProcDecl, rid: usize) -> Result<(), String> {
        line(out, 0, format!("def _proc_{pid}_{rid}(env, pc, args):"));
        line(out, 1, "while True:");
        line(out, 2, "match pc:");
        for &id in p.graph.regions[rid].nodes.iter() {
            line(out, 3, format!("case {id}:  # {}", self.name(id)?));
            let node = &self.prog.nodes[id as usize];
            let result = match &node.kind {
                NodeKind::Sig(_) => {
                    let fields = self
                        .params(id)?
                        .iter()
                        .enumerate()
                        .map(|(i, f)| format!("{}=args[{i}]", ident(&f.name)))
                        .collect::<Vec<_>>();
                    format!("{}({})", self.ty(&self.ret(id)?)?, fields.join(", "))
                }
                NodeKind::Id(_) => "args[0]".into(),
                _ => format!(
                    "_vd_runtime.invoke({}, {}, args)",
                    quote(&self.name(id)?),
                    self.callable(id)?
                ),
            };
            line(out, 4, format!("this = env[{id}] = {result}"));
            match p.graph.edges.get(&id) {
                None => line(
                    out,
                    4,
                    format!(
                        "return {}",
                        self.cast("this".into(), &self.ret(id)?, Some(&p.ret))?
                    ),
                ),
                Some(SEdge::Call(c)) => self.transition(out, 4, c)?,
                Some(SEdge::Collect(_)) => line(out, 4, "return this"),
                Some(SEdge::Match(arms)) => self.arms(out, 4, arms)?,
                Some(SEdge::ForEach(f)) => {
                    let region = p.graph.opens[&id];
                    let dim = self.expr(&f.dim, Some(&Type::Array(f.elem.clone().into())))?;
                    line(
                        out,
                        4,
                        format!(
                            "this = _vd_runtime.fan_out(lambda this: _proc_{pid}_{region}(env.copy(), {}, {}), {dim})",
                            f.call.target,
                            self.args(&f.call)?
                        ),
                    );
                    let collect = gen_leaf::collect_call(p.graph.clone(), id)?;
                    self.transition(out, 4, &collect)?;
                }
                Some(SEdge::Spawn(s)) => {
                    let mut joined = Vec::new();
                    let mut names = Vec::new();
                    for (i, branch) in s.branches.iter().enumerate() {
                        let c = &branch.call;
                        line(
                            out,
                            4,
                            format!(
                                "branch_{i} = ({}, {}, {})",
                                quote(&self.name(c.target)?),
                                self.callable(c.target)?,
                                self.args(c)?
                            ),
                        );
                    }
                    for (i, branch) in s.branches.iter().enumerate() {
                        let c = &branch.call;
                        if branch.detach {
                            line(
                                out,
                                4,
                                format!("_vd_runtime.detached(_vd_runtime.invoke, branch_{i})"),
                            );
                        } else {
                            if !sema_leaf::is_void(self.ret(c.target)?)? {
                                let name = self.prog.nodes[c.target as usize]
                                    .qual
                                    .last()
                                    .ok_or("anonymous spawn target")?;
                                names.push(format!("{}=results[{}]", ident(name), joined.len()));
                            }
                            joined.push(format!("(_vd_runtime.invoke, branch_{i})"));
                        }
                    }
                    line(
                        out,
                        4,
                        format!("results = _vd_runtime.join({})", tup(joined)),
                    );
                    line(
                        out,
                        4,
                        format!("this = {}({})", self.ty(&s.joined)?, names.join(", ")),
                    );
                    self.transition(out, 4, &s.join)?;
                }
            }
        }
        line(out, 3, "case _:");
        line(
            out,
            4,
            "raise _vd_runtime.VandorfError(f'invalid state {pc}')",
        );
        out.push('\n');
        Ok(())
    }

    fn signature(
        &self,
        params: &[Member],
        ret: &Type,
        name: &str,
        qualified: bool,
    ) -> Result<String, String> {
        let display = |t| {
            self.ty(t).map(|s| {
                if qualified {
                    s
                } else {
                    s.replace("_vd_types.", "").replace("type(None)", "None")
                }
            })
        };
        let args = params
            .iter()
            .map(|p| Ok(format!("{}: {}", ident(&p.name), display(&p.ty)?)))
            .collect::<Result<Vec<_>, String>>()?;
        Ok(format!(
            "def {name}({}) -> {}",
            args.join(", "),
            display(ret)?
        ))
    }

    fn check_impl(
        &mut self,
        file: &Str,
        function: &Str,
        f: &FuncDecl,
        name: &str,
    ) -> Result<(), String> {
        if !self.implementations.contains_key(file) {
            self.implementations
                .insert(file.clone(), check_module(file)?);
        }
        match &self.implementations[file] {
            ModuleCheck::Unchecked => Ok(()),
            ModuleCheck::Signatures(signatures) if signatures.contains_key(&**function) => {
                let args = &signatures[&**function];
                let count = f.params.len();
                if args.requires_keywords_or_async
                    || count < args.minimum
                    || args.maximum.is_some_and(|max| count > max)
                {
                    let sig = self.signature(&f.params, &f.ret, function, false)?;
                    return Err(format!(
                        "{name}: Python implementation {file}:{function} cannot be called synchronously with {count} positional arguments\n  expected {sig}"
                    ));
                }
                Ok(())
            }
            _ => {
                let sig = self.signature(&f.params, &f.ret, function, false)?;
                self.warnings.push(format!("warning: {name}: no Python definition {function} in {file}\n  expected {sig}").into());
                Ok(())
            }
        }
    }

    fn procs(&mut self, s: &PythonInput) -> Result<String, String> {
        let mut out = format!(
            "{HEADER}from __future__ import annotations\nfrom . import types as _vd_types\nfrom . import _runtime as _vd_runtime\n\n\ndef _identity(value):\n    return value\n\n"
        );
        let mut proc_names = std::collections::BTreeSet::new();
        for (i, node) in self.prog.nodes.iter().enumerate() {
            let id = i as i64;
            match &node.kind {
                NodeKind::Proc(p) => {
                    let name = self.proc_name(id)?;
                    if !proc_names.insert(name.clone()) {
                        return Err(format!("Python proc name {name} is ambiguous"));
                    }
                    let params = self.params(id)?;
                    line(
                        &mut out,
                        0,
                        format!("@_vd_runtime.proc({})", quote(&self.name(id)?)),
                    );
                    line(
                        &mut out,
                        0,
                        format!("{}:", self.signature(&params, &p.ret, &name, true)?),
                    );
                    if !node.doc.is_empty() {
                        line(&mut out, 1, quote(&node.doc));
                    }
                    let args = params
                        .iter()
                        .map(|p| {
                            Ok(format!(
                                "_vd_runtime.value({}, {})",
                                ident(&p.name),
                                self.ty(&p.ty)?
                            ))
                        })
                        .collect::<Result<Vec<_>, String>>()?;
                    line(
                        &mut out,
                        1,
                        format!("return _proc_{id}_0({{}}, {}, {})", p.entry, tup(args)),
                    );
                    out.push('\n');
                    for rid in 0..p.graph.regions.len() {
                        self.machine(&mut out, id, p, rid)?;
                    }
                }
                NodeKind::Func(f) => {
                    let imp = f.imps.iter().find(|r| r.file.ends_with(".py"));
                    let param_values = f
                        .params
                        .iter()
                        .map(|p| {
                            Ok(format!(
                                "_vd_runtime.value({}, {})",
                                ident(&p.name),
                                self.ty(&p.ty)?
                            ))
                        })
                        .collect::<Result<Vec<_>, String>>()?;
                    line(
                        &mut out,
                        0,
                        format!(
                            "{}:",
                            self.signature(&f.params, &f.ret, &format!("_func_{id}"), true)?
                        ),
                    );
                    let name = self.name(id)?;
                    if let Some(imp) = imp {
                        let file = if Path::new(&*imp.file).is_absolute() {
                            imp.file.clone()
                        } else {
                            cli_leaf::join(s.out.clone(), imp.file.clone())?
                        };
                        if s.check_impls {
                            self.check_impl(&file, &imp.function, f, &name)?;
                        }
                        line(
                            &mut out,
                            1,
                            format!(
                                "_vd_implementation = _vd_runtime.implementation({}, {})",
                                quote(&imp.file),
                                quote(&imp.function)
                            ),
                        );
                        line(
                            &mut out,
                            1,
                            format!(
                                "return _vd_runtime.value(_vd_implementation({}), {})",
                                param_values.join(", "),
                                self.ty(&f.ret)?
                            ),
                        );
                    } else {
                        let function = node.qual.last().ok_or("unnamed func")?;
                        let sig = self.signature(&f.params, &f.ret, &ident(function), false)?;
                        self.warnings.push(
                            format!("warning: {name}: no Python implementation\n  expected {sig}")
                                .into(),
                        );
                        line(
                            &mut out,
                            1,
                            format!(
                                "raise _vd_runtime.VandorfError({})",
                                quote(&format!(
                                    "no Python implementation for {name}; expected {sig}"
                                ))
                            ),
                        );
                    }
                    out.push('\n');
                }
                _ => {}
            }
        }
        Ok(out)
    }

    fn top(&self, entry: &Str, owner: &str) -> Result<i64, String> {
        let id = gen_leaf::find_top(self.prog.clone(), entry.clone())?;
        if id < 0 {
            Err(format!(
                "{owner} runs proc {entry}, but there is no top-level proc {entry}"
            ))
        } else {
            Ok(id)
        }
    }

    fn params_literal(&self, params: &[Member]) -> Result<String, String> {
        Ok(tup(params
            .iter()
            .map(|p| Ok(format!("({}, {})", quote(&p.name), self.ty(&p.ty)?)))
            .collect::<Result<Vec<_>, String>>()?))
    }

    fn command(&self, name: &str, id: i64) -> Result<String, String> {
        let params = self.params(id)?;
        let varargs = params.len() == 1
            && matches!(self.unfold(&params[0].ty)?, Type::Array(t) if matches!(self.unfold(&t)?, Type::Prim(p) if &*p == "string"));
        let mut usage = format!("usage: {name}");
        if varargs {
            write!(usage, " <{}...>", params[0].name).unwrap();
        } else {
            for p in params.iter() {
                match self.unfold(&p.ty)? {
                    Type::Prim(t) if &*t != "void" => write!(usage, " <{}: {t}>", p.name).unwrap(),
                    _ => {
                        return Err(format!(
                            "{name}: parameter {} must be int, float, bool or string (or a single []string)",
                            p.name
                        ));
                    }
                }
            }
        }
        Ok(format!(
            "(P.{}, {}, {}, {})",
            self.proc_name(id)?,
            self.params_literal(&params)?,
            self.ty(&self.ret(id)?)?,
            quote(&usage)
        ))
    }

    fn launch_path(&self, name: &str, custom: &MaybeStr, s: &PythonInput) -> Result<Str, String> {
        match custom {
            MaybeStr::None => cli_leaf::join(
                cli_leaf::parent(s.out.clone())?,
                format!("{name}.py").into(),
            ),
            MaybeStr::Some(path) => cli_leaf::join(s.root.clone(), path.clone()),
        }
    }

    fn launcher(&self, s: &PythonInput, path: &Str, call: &str) -> Result<String, String> {
        let package = Path::new(&*s.out)
            .file_name()
            .and_then(|p| p.to_str())
            .ok_or("Python out must name a package directory")?;
        let base = cli_leaf::relative(
            cli_leaf::parent(s.out.clone())?,
            cli_leaf::parent(path.clone())?,
        )?;
        Ok(format!(
            "{HEADER}from importlib import import_module\nfrom pathlib import Path\nimport sys\n\nif __name__ == \"__main__\":\n    sys.path.insert(0, str(Path(__file__).resolve().parent / {}))\n    P = import_module({})\n    _vd_types = import_module({})\n    entry = import_module({})\n    {call}\n",
            quote(&base),
            quote(&format!("{package}.procs")),
            quote(&format!("{package}.types")),
            quote(&format!("{package}._entry"))
        ))
    }

    fn server(&self, server: &GoServerSpec) -> Result<String, String> {
        let owner = format!("http server {}", server.name);
        let setup = if server.setup.is_empty() {
            None
        } else {
            let id = self.top(&server.setup, &owner)?;
            if !self.params(id)?.is_empty() {
                return Err(format!("{owner}: setup must take no parameters"));
            }
            Some(id)
        };
        let routes = |routes: &[Route], raw| -> Result<String, String> {
            let mut result = Vec::new();
            for r in routes {
                let id = self.top(&r.proc, &owner)?;
                let params = self.params(id)?;
                let params = if let Some(setup) = setup {
                    let Some((ctx, rest)) = params.split_first() else {
                        return Err(format!("{owner}: {} must take ctx", r.proc));
                    };
                    if &*ctx.name != "ctx" || self.ty(&ctx.ty)? != self.ty(&self.ret(setup)?)? {
                        return Err(format!(
                            "{owner}: {} must take the setup result as ctx",
                            r.proc
                        ));
                    }
                    rest
                } else {
                    &params
                };
                let spec = if raw {
                    if params.len() != 1
                        || !gen_leaf::raw_shape(self.prog, &params[0].ty, gen_leaf::RAW_REQUEST)
                        || !gen_leaf::raw_shape(self.prog, &self.ret(id)?, gen_leaf::RAW_RESPONSE)
                    {
                        return Err(format!(
                            "{owner}: {} must take a raw request and return a raw response",
                            r.proc
                        ));
                    }
                    self.ty(&params[0].ty)?
                } else {
                    self.params_literal(params)?
                };
                result.push(format!(
                    "({}, {}): (P.{}, {spec})",
                    quote(&r.method),
                    quote(&r.path),
                    self.proc_name(id)?
                ));
            }
            result.sort();
            Ok(format!("{{{}}}", result.join(", ")))
        };
        let json = routes(&server.routes, false)?;
        let raw = routes(&server.raw, true)?;
        let mut statics = server
            .statics
            .iter()
            .map(|f| {
                format!(
                    "(\"GET\", {}): ({}, {})",
                    quote(&f.url),
                    quote(&f.ctype),
                    quote(&f.text)
                )
            })
            .collect::<Vec<_>>();
        statics.sort();
        let statics = format!("{{{}}}", statics.join(", "));
        let setup = setup
            .map(|id| self.proc_name(id).map(|n| format!("P.{n}")))
            .transpose()?
            .unwrap_or_else(|| "None".into());
        let cli = if server.cli.is_empty() {
            "None".into()
        } else {
            let id = gen_leaf::cli_entry(self.prog, &server.name, &server.cli)?;
            format!("P.{}", self.proc_name(id)?)
        };
        Ok(format!(
            "entry.server({}, {json}, {raw}, {statics}, setup={setup}, cli={cli})",
            quote(&server.addr)
        ))
    }

    fn files(&mut self, s: &PythonInput) -> Result<Vec<OutFile>, String> {
        let mut files = Vec::new();
        for (name, text, kind) in [
            ("types.py", self.types(), "types"),
            ("procs.py", self.procs(s)?, "code"),
            ("_runtime.py", RUNTIME.into(), "code"),
            ("_entry.py", HTTP.into(), "code"),
            (
                "__init__.py",
                format!("{HEADER}from ._runtime import VandorfError\n"),
                "code",
            ),
        ] {
            files.push(OutFile {
                path: cli_leaf::join(s.out.clone(), name.into())?,
                text: text.into(),
                kind: kind.into(),
            });
        }
        let mut names: Vec<_> = s
            .bins
            .keys()
            .filter(|n| s.only.is_empty() || *n == &s.only)
            .collect();
        names.sort();
        for name in names {
            let bin = &s.bins[name];
            let path = self.launch_path(name, &bin.python, s)?;
            let call = self.command(name, self.top(&bin.entry, name)?)?;
            files.push(OutFile {
                text: self
                    .launcher(s, &path, &format!("entry.command(*{call}, sys.argv[1:])"))?
                    .into(),
                path,
                kind: "main".into(),
            });
        }
        for server in s.servers.iter() {
            let path = self.launch_path(&server.name, &s.http[&server.name].python, s)?;
            files.push(OutFile {
                text: self.launcher(s, &path, &self.server(server)?)?.into(),
                path,
                kind: "main".into(),
            });
        }
        let mut paths = std::collections::BTreeSet::new();
        for f in &files {
            if !paths.insert(&f.path) {
                return Err(format!(
                    "Python output path {} is written more than once",
                    f.path
                ));
            }
        }
        Ok(files)
    }
}
